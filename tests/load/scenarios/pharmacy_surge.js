import http from 'k6/http';
import { check, sleep } from 'k6';
import { globalThresholds, getBaseHeaders } from '../configs/thresholds.js';
import { createPharmacyQRToken } from '../shared/auth.js';

export const options = {
    scenarios: {
        pharmacy_surge: {
            executor: 'ramping-vus',
            startVUs: 0,
            stages: [
                { duration: '5m', target: 500 },
                { duration: '10m', target: 500 },
                { duration: '2m', target: 0 }
            ],
            gracefulRampDown: '30s',
            tags: { scenario: 'pharmacy', priority: 'critical' }
        }
    },
    thresholds: globalThresholds
};

const API_HOST = __ENV.API_HOST || 'http://host.docker.internal:8000';

export default function () {
    // 1. Generate QR (Patient Side)
    // Assume policy ID 1-10000 generated by seed script
    const policyId = Math.floor(Math.random() * 10000) + 1;

    // Test the QR generation endpoint (assuming we're generating JWTs locally for load testing auth)
    const token = createPharmacyQRToken(policyId);

    const qrPayload = JSON.stringify({
        policy_id: policyId,
        metadata: { source: 'k6_load_test' }
    });

    // We mock the generation time here if local auth, or call endpoint if auth allows
    const qrRes = http.post(`${API_HOST}/api/pharmacy/qr/generate`, qrPayload, {
        headers: getBaseHeaders(),
        tags: { name: 'qr_generate' }
    });

    // If endpoint is protected, we just simulate verification of valid token
    // 2. Verify QR (Pharmacy Side)
    // Assume pharmacy ID 1-500
    const pharmacyId = Math.floor(Math.random() * 500) + 1;

    const verifyPayload = JSON.stringify({
        token: token,
        pharmacy_id: pharmacyId,
        scanned_at: new Date().toISOString()
    });

    const verifyRes = http.post(`${API_HOST}/api/pharmacy/qr/verify`, verifyPayload, {
        headers: getBaseHeaders(),
        tags: { name: 'qr_verify' }
    });

    check(verifyRes, {
        'status is 200': (r) => r.status === 200,
        'response time < 200ms': (r) => r.timings.duration < 200,
        'valid verification': (r) => {
            try { return r.json('status') !== undefined; } catch (e) { return false; }
        }
    });

    // Respect rate limits during ramping
    sleep(1);
}
