from fpdf import FPDF
from datetime import datetime
import os

class CertificatePDF(FPDF):
    def header(self):
        # Logo could go here
        self.set_font('Helvetica', 'B', 20)
        self.cell(0, 10, 'Wali Micro-Insurance', align='C', new_x="LMARGIN", new_y="NEXT")
        self.ln(10)

    def footer(self):
        self.set_y(-15)
        self.set_font('Helvetica', 'I', 8)
        self.cell(0, 10, f'Page {self.page_no()}', align='C')

def generate_policy_certificate(policy_data: dict) -> bytes:
    """Generate a PDF certificate for a policy."""
    pdf = CertificatePDF()
    pdf.add_page()
    
    # Title
    pdf.set_font('Helvetica', 'B', 16)
    pdf.cell(0, 10, 'CERTIFICATE OF INSURANCE', align='C', new_x="LMARGIN", new_y="NEXT")
    pdf.ln(10)
    
    # Policy Information
    pdf.set_font('Helvetica', '', 12)
    
    # Helper to add rows
    def add_row(label, value):
        pdf.set_font('Helvetica', 'B', 12)
        pdf.cell(50, 10, label, border=1)
        pdf.set_font('Helvetica', '', 12)
        pdf.cell(0, 10, str(value), border=1, new_x="LMARGIN", new_y="NEXT")

    add_row("Policy Number", policy_data.get("policy_number", "N/A"))
    add_row("Status", policy_data.get("status", "N/A").upper())
    add_row("Coverage Type", policy_data.get("coverage_type", "N/A").title())
    add_row("Premium", f"{policy_data.get('premium_amount')} XOF")
    add_row("Frequency", policy_data.get("payment_frequency", "N/A").title())
    
    # Dates
    pdf.ln(5)
    start_date = policy_data.get("start_date")
    if start_date:
        # Format date if it's a string from JSON
        if isinstance(start_date, str):
            try:
                dt = datetime.fromisoformat(start_date)
                start_date = dt.strftime("%Y-%m-%d")
            except:
                pass
    
    add_row("Effective Date", start_date or "Pending Activation")
    
    # Coverage Details
    pdf.ln(10)
    pdf.set_font('Helvetica', 'B', 14)
    pdf.cell(0, 10, 'Coverage Details', new_x="LMARGIN", new_y="NEXT")
    pdf.set_font('Helvetica', '', 12)
    
    details = policy_data.get("coverage_details", {})
    if details:
        for k, v in details.items():
            key_formatted = k.replace("_", " ").title()
            pdf.cell(0, 8, f"- {key_formatted}: {v}", new_x="LMARGIN", new_y="NEXT")
            
    # Allow digital signature space
    pdf.ln(20)
    pdf.set_font('Helvetica', 'I', 12)
    pdf.cell(0, 10, "This certificate is digitally generated by Wali.", align='C', new_x="LMARGIN", new_y="NEXT")
    
    return pdf.output()
